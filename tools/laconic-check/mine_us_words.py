#!/usr/bin/env python3
"""Generate src/us_words.txt: US spellings of words the Style Manual spells the Australian way.

Every word in the Australian Government Style Manual scrape is taken as an accepted
Australian spelling. For each one with a British/Australian pattern (-our, -ise, -yse,
-tre, -ogue, -ence, doubled l before -ed/-ing), the US form is generated, and kept only
when that form never appears in the manual itself. Run from the repository root:

    python tools/laconic-check/mine_us_words.py
"""

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
MANUAL = ROOT / "skills/laconic-prose/references/australian-government-style-manual.md"
OUT = ROOT / "tools/laconic-check/src/us_words.txt"

DOUBLE_L_STEMS = ("travel", "cancel", "label", "model", "signal", "total", "level", "fuel", "dial",
                  "channel", "counsel", "marshal", "equal", "tunnel", "funnel", "jewel", "pencil", "quarrel")
RULES = [
    # colour -> color, but not pour, four, tour, hour, detour and similar.
    (r"(?<=[bcdghlmnrv])our(s|ed|ing|ite|ites|able|ably|er|ers|ful|less)?$", r"or\1"),
    # organise -> organize, only after endings that US -ize verbs use.
    (r"(?<=al|an|ar|en|er|il|it|on|or|ot|og|ag|ph|th|ic|em|om|im|gn|ul|ri|et|at|ch|ss)is(e|es|ed|ing|ation|ations|er|ers)$", r"iz\1"),
    (r"ys(e|es|ed|ing)$", r"yz\1"),
    (r"tre(s)?$", r"ter\1"),
    (r"tred$", r"tered"),
    (r"ogue(s)?$", r"og\1"),
    (r"(def|off|pret)ence$", r"\1ense"),
]
# US-looking forms that are also standard Australian words or names: meter (a measuring
# device), dialog (a software dialog box), Labor (the party), program, and short
# fragments of place names.
KEEP = {"meter", "meters", "dialog", "dialogs", "labor", "program", "programs", "nambor", "seymor", "yanizes"}
# Words ending in -ise that keep -ise in US English too.
NOT_ISE_STEMS = ("advis", "revis", "devis", "supervis", "televis", "surpris", "compris", "compromis",
                 "enterpris", "exercis", "expertis", "franchis", "merchandis", "premis", "promis",
                 "precis", "concis", "despis", "demis", "disguis", "excis", "incis", "chastis",
                 "improvis", "otherwis", "likewis", "treatis", "repris", "denis", "nois", "rais",
                 "prais", "aris", "wis", "pois", "cruis", "bruis", "guis", "paradis")


def main() -> None:
    text = MANUAL.read_text(encoding="utf-8").lower()
    words = set(re.findall(r"[a-z]+", text))
    pairs = {}
    for au in sorted(words):
        if len(au) < 5 or au.startswith(NOT_ISE_STEMS):
            continue
        candidates = [re.sub(pattern, repl, au) for pattern, repl in RULES]
        for stem in DOUBLE_L_STEMS:
            for single, double in (("led", "lled"), ("ling", "lling"), ("ler", "ller"), ("lers", "llers")):
                if au == stem + double[1:]:
                    candidates.append(stem + single[1:])
        for us in candidates:
            if us != au and us not in words and us not in KEEP and len(us) >= 5:
                pairs[us] = au
    lines = [f"{us} {au}" for us, au in sorted(pairs.items())]
    header = (
        "# US spelling -> Australian spelling, generated by mine_us_words.py from the\n"
        "# Australian Government Style Manual (Commonwealth of Australia, CC BY 4.0).\n"
    )
    OUT.write_text(header + "\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(lines)} pairs written to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
